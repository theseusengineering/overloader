def read_rows():
    with CSV_PATH.open(newline="", encoding="utf-8-sig") as handle:
        return list(csv.DictReader(handle))


def build_exercises(rows):
    exercises = {}
    for row in rows:
        original_name = clean(row["Exercise Name"])
        display_name = NAME_NORMALISATIONS.get(original_name, original_name)
        exercise_id = exercise_id_for(original_name)
        if exercise_id in exercises:
            continue
        exercises[exercise_id] = {
            "id": exercise_id,
            "name": display_name,
            "category": infer_category(display_name),
            "equipment": infer_equipment(display_name),
            "location": infer_location(display_name),
            "increment": infer_increment(display_name),
            "repMin": infer_rep_min(display_name),
            "repMax": infer_rep_max(display_name),
            "targetRpe": 8,
            "defaultWarmupSets": 1 if needs_default_warmup(display_name) else 0,
            "defaultWorkingSets": 3,
            "loadMode": infer_load_mode(display_name),
            "needsReview": False,
            "notes": "Imported from Strong export"
        }
    return dict(sorted(exercises.items(), key=lambda item: item[1]["name"].lower()))


def build_history(rows, exercises):
    grouped = defaultdict(list)
    for index, row in enumerate(rows):
        date = clean(row["Date"])
        workout = clean(row["Workout Name"]) or "Imported Workout"
        exercise_name = clean(row["Exercise Name"])
        grouped[(date, workout, exercise_id_for(exercise_name))].append((index, row))

    history = []
    for (date, workout, exercise_id), set_rows in sorted(grouped.items(), key=lambda item: (item[0][0], item[0][1], item[0][2])):
        exercise = exercises[exercise_id]
        sets = []
        exercise_note = ""
        workout_note = ""
        for order, row in set_rows:
            set_type = set_type_for(row["Set Order"])
            note = clean(row.get("Notes", ""))
            if note and not exercise_note:
                exercise_note = note
            workout_note_value = clean(row.get("Workout Notes", ""))
            if workout_note_value and not workout_note:
                workout_note = workout_note_value
            sets.append({
                "id": f"strong-set-{stable_slug(date, workout, exercise_id, str(order))}",
                "order": len(sets),
                "type": set_type,
                "weight": parse_weight(row["Weight"], exercise),
                "reps": parse_number(row["Reps"], integer=True) or 0,
                "rpe": parse_number(row["RPE"]),
                "rir": rpe_to_rir(parse_number(row["RPE"])),
                "completed": True,
            })
        history.append({
            "id": f"strong-perf-{stable_slug(date, workout, exercise_id)}",
            "sessionId": f"strong-session-{stable_slug(date, workout)}",
            "exerciseId": exercise_id,
            "workoutName": workout,
            "location": infer_location_from_workout(workout, exercise["location"]),
            "performedAt": local_iso(date),
            "note": exercise_note,
            "workoutNote": workout_note,
            "sets": sets,
        })
    return history


def exercise_id_for(name):
    if name in EXISTING_EXERCISE_IDS:
        return EXISTING_EXERCISE_IDS[name]
    return stable_slug(NAME_NORMALISATIONS.get(name, name))


def set_type_for(value):
    value = clean(value)
    if value == "W":
        return "warmup"
    if value == "D":
        return "dropset"
    if value == "F":
        return "failure"
    return "working"


def parse_weight(value, exercise):
    number = parse_number(value)
    if number is None:
        return None
    if exercise["loadMode"] == "bodyweight":
        return None
    if exercise["loadMode"] == "assisted":
        return -abs(number)
    return number


def parse_number(value, integer=False):
    value = clean(value)
    if value == "":
        return None
    number = float(value)
    if integer:
        return int(number)
    if number.is_integer():
        return int(number)
    return number


def rpe_to_rir(rpe):
    if rpe is None:
        return None
    rir = max(0, min(10, 10 - float(rpe)))
    return int(rir) if rir.is_integer() else round(rir, 1)


def infer_category(name):
    for needle, category in CATEGORY_HINTS:
        if needle.lower() in name.lower():
            return category
    return "Other"


def infer_equipment(name):
    lowered = name.lower()
    if "barbell" in lowered:
        return "barbell"
    if "dumbbell" in lowered:
        return "dumbbell"
    if "cable" in lowered:
        return "cable"
    if "plate loaded" in lowered:
        return "plate-loaded"
    if "smith" in lowered:
        return "smith-machine"
    if "band" in lowered:
        return "band"
    if "kettlebell" in lowered:
        return "kettlebell"
    if "machine" in lowered:
        return "machine"
    if name in BODYWEIGHT_NAMES:
        return "bodyweight"
    return "machine"


def infer_location(name):
    if "Balmain Fitness" in name:
        return "Balmain Fitness"
    return "Imported Strong"


def infer_location_from_workout(workout_name, exercise_location):
    if "Balmain Fitness" in workout_name or "Balmain" in exercise_location:
        return "Balmain Fitness"
    return exercise_location


def infer_increment(name):
    lowered = name.lower()
    if "jpg kneeled" in lowered or "lat pulldown single arm" in lowered:
        return 1.25
    if "dumbbell" in lowered:
        return 2
    if "barbell" in lowered or "plate loaded" in lowered:
        return 2.5
    if "leg press" in lowered:
        return 5
    return 2.5


def infer_rep_min(name):
    lowered = name.lower()
    if "jpg kneeled" in lowered:
        return 20
    if "calf" in lowered or "lateral raise" in lowered:
        return 10
    return 8


def infer_rep_max(name):
    lowered = name.lower()
    if "jpg kneeled" in lowered:
        return 28
    if "calf" in lowered or "lateral raise" in lowered:
        return 15
    return 12


def needs_default_warmup(name):
    return infer_load_mode(name) == "external" and infer_equipment(name) not in {"bodyweight", "band"}


def infer_load_mode(name):
    if "(Assisted)" in name:
        return "assisted"
    if name in BODYWEIGHT_NAMES:
        return "bodyweight"
    return "external"


def local_iso(value):
    date, time = value.split(" ")
    return f"{date}T{time}"


def clean(value):
    return "" if value is None else str(value).strip()


def stable_slug(*parts):
    text = "-".join(clean(part) for part in parts if clean(part))
    text = text.lower().replace("&", "and")
    text = re.sub(r"[^a-z0-9]+", "-", text)
    return text.strip("-")


